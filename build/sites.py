"""Площадка по коду завода SAP — общее правило для остатков и потребности.

  11xx, 7101, 7106 (перевалочная база КБЕ)      -> 1100 Красноярск / Еруда
  14xx, 7104                                    -> 1400 Магадан
  12xx, 24xx, 7102, 7108 (перевалочная база ПВ) -> 2400 Сухой Лог
  13xx, 7103                                    -> 1300 Алдан

WK в Иркутской области работают только на Сухом Логе, а их заказы ТОРО
планирует завод 1200 (Вернинское), поэтому склады Вернинского и «Развитие»
Иркутские активы относятся к площадке Сухой Лог. То же правило — в
lib/stock_pipeline.js и lib/wk_update_pipeline.js.
"""

SITE_NAMES = {"1100": "Красноярск / Еруда", "1400": "Магадан", "2400": "Сухой Лог", "1300": "Алдан"}
PLANT_SITE = {"7101": "1100", "7106": "1100", "7104": "1400", "7102": "2400", "7108": "2400", "7103": "1300"}
PREFIX_SITE = {"11": "1100", "14": "1400", "12": "2400", "24": "2400", "13": "1300"}
TRANSIT_PLANTS = {"110C", "1208", "7106", "7108"}


def plant_site(plant):
    """Площадка по коду завода SAP."""
    p = str(plant or "").strip().upper()
    return PLANT_SITE.get(p) or PREFIX_SITE.get(p[:2], "")
